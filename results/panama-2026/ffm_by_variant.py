"""ffm_sign per pair-frame and the pooled sign decision, with and without the pairs excluded by EXCLUSION_CRITERION.md.
Run from backend/ (NISAR_LOS_SIGN unset), one process per variant, like sensitivity_iono.py:
    python ../results/panama-2026/ffm_by_variant.py A|B|C      # writes ffm_by_variant_<V>.json
    python ../results/panama-2026/ffm_by_variant.py merge      # writes ffm_by_variant.md
A = old already_applied (raw phase), B = fixed code, C = forced subtraction (monkeypatch of keep_raw_phase, script only).
The excluded pairs come from zero_sigma_diagnosis.json (rules 1 and 2 of the criterion), never from a fit result.
"""
from __future__ import annotations

import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
OUT = Path(__file__).resolve().parent
VARIANT = sys.argv[1] if len(sys.argv) > 1 else "B"

import config  # noqa: E402
from recipes import corrections  # noqa: E402

if VARIANT == "A":
    def _old(name, attrs):
        desc = ((attrs.get("datasets") or {}).get("unwrappedPhase") or {}).get("description", "").lower()
        if name in desc and any(w in desc for w in ("corrected", "applied", "removed")):
            return True
        hits = [v for k, v in (attrs.get("flags") or {}).items() if name in k.lower() and "applied" in k.lower()]
        if any(v.strip().lower() in corrections._TRUE for v in hits):
            return True
        return None if attrs.get("source") is None else False
    corrections.already_applied = _old
elif VARIANT == "C":
    corrections.keep_raw_phase = lambda *a, **k: False


def geometry(p) -> str:
    return f"T{p.track} {p.direction[:4]}"


def merge() -> None:
    D = {v: json.loads((OUT / f"ffm_by_variant_{v}.json").read_text(encoding="utf-8")) for v in "ABC"}
    L = ["# ffm_sign per pair-frame, variants A / B / C, with and without the excluded pairs (generated by ffm_by_variant.py)", "",
         "k is the scale of the USGS finite-fault model against the data (a scale-free ratio, only its sign and significance are used). "
         "sigma_k ignores spatial correlation (`ffm_sign.py:74-77`). Verdict: consistent = k > 0 at > 3 sigma; flipped = k < 0 at > 3 sigma.", ""]
    for v, d in D.items():
        L += [f"## Variant {v}", "", "| Pair-frame | Geometry | k | sigma_k | k/sigma | Verdict | Excluded by the criterion |", "|---|---|---|---|---|---|---|"]
        for r in d["per_frame"]:
            L.append(f"| {r['pair']}{' (' + r['variant_note'] + ')' if r.get('variant_note') else ''} | {r['geometry']} | {r['k']:.4g} | {r['sigma_k']:.3g} | {r['k_over_sigma']:+.1f} | {r['verdict']} | {r['excluded']} |")
        for label, key in (("all pair-frames", "counts_all"), ("without the excluded pairs", "counts_kept")):
            c = d[key]
            L.append("")
            L.append(f"- **{label}:** {c['n_frames']} frames; consistent {c['n_consistent_frames']}, flipped {c['n_flipped_frames']}, inconclusive {c['n_inconclusive_frames']}. "
                     f"Distinct tracks with a consistent frame: {c['n_tracks_consistent']} ({', '.join(c['tracks_consistent'])}); distinct geometries (track + direction): {c['n_geometries_consistent']}; "
                     f"ascending / descending geometries among them: {c['n_asc']} / {c['n_desc']}.")
        d1, d2 = d["decision_all"], d["decision_kept"]
        L += ["", "| Pooled decision inputs | all pairs | without excluded |", "|---|---|---|"]
        for k in ("decision", "vr_plus1", "vr_minus1", "vr_difference", "best_plane_plus1", "ffm_n_k_positive_3sigma", "ffm_n_k_negative_3sigma"):
            L.append(f"| {k} | {d1.get(k)} | {d2.get(k)} |")
        L += ["", "Per track without the excluded pairs (best plane):", "", "| Track | VR(+1) | VR(-1) | Diff |", "|---|---|---|---|"]
        for t, r in d["per_track_kept"].items():
            L.append(f"| {t} | {r['vr_plus1']} | {r['vr_minus1']} | {r['diff']} |")
        L.append("")
    (OUT / "ffm_by_variant.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written ffm_by_variant.md")


if VARIANT == "merge":
    merge()
    sys.exit(0)

import catalog  # noqa: E402
from science import ffm_sign, panama_fault as pf, sign_decision, usgs  # noqa: E402
from science.invert_fault import fit_plane  # noqa: E402

diag = json.loads((OUT / "zero_sigma_diagnosis.json").read_text(encoding="utf-8"))
excluded_ids = {k for k, r in diag.items() if r["excluded_rule1"] or r["excluded_rule2"]}
ev = usgs.event("us6000u18k")
origin = datetime.fromtimestamp(ev.time_ms / 1000, tz=timezone.utc).strftime("%Y%m%dT%H%M%S")
pairs = catalog.straddling(catalog.find(ev.lat, ev.lon, "GUNW"), origin)
t0 = time.time()
items = []
for p in pairs:
    t = pf.track_from_product(p, ev.lat, ev.lon)
    if t is not None:
        items.append((p, t))
tracks_all = [t for _, t in items]
models = ffm_sign.forward(ffm_sign.USGS_FFM_PANAMA, tracks_all, ev.lat, ev.lon)
seen_ids, per_frame = {}, []
for (p, t), m in zip(items, models):
    r = ffm_sign.scale_fit(t.los, m, t.east, t.north, t.comp)
    n = seen_ids.get(p.id, 0)
    seen_ids[p.id] = n + 1
    per_frame.append({"pair": p.id, "variant_note": "second product variant" if n else ("two product variants share this id" if sum(q.id == p.id for q, _ in items) > 1 else ""),
                      "geometry": geometry(p), "track": f"T{p.track}", "k": r["k"], "sigma_k": r["sigma_k"],
                      "k_over_sigma": r["k"] / r["sigma_k"] if r["sigma_k"] else 0.0, "verdict": r["verdict"], "excluded": p.id in excluded_ids})


def counts(rows):
    cons = [r for r in rows if r["verdict"] == "consistent"]
    geos = sorted({r["geometry"] for r in cons})
    return {"n_frames": len(rows), "n_consistent_frames": len(cons), "n_flipped_frames": sum(r["verdict"] == "flipped" for r in rows),
            "n_inconclusive_frames": sum(r["verdict"] == "inconclusive" for r in rows),
            "tracks_consistent": sorted({r["track"] for r in cons}), "n_tracks_consistent": len({r["track"] for r in cons}),
            "geometries_consistent": geos, "n_geometries_consistent": len(geos),
            "n_asc": sum("asce" in g for g in geos), "n_desc": sum("desc" in g for g in geos)}


def decide(tracks):
    d = sign_decision.decide(tracks, ev.planes, ev.lat, ev.lon)
    return {"decision": d["decision"], "ffm_n_k_positive_3sigma": d["ffm"]["n_k_positive_3sigma"],
            "ffm_n_k_negative_3sigma": d["ffm"]["n_k_negative_3sigma"],
            "vr_plus1": round(d["inversion"]["variance_reduction_plus1"], 4),
            "vr_minus1": round(d["inversion"]["variance_reduction_minus1"], 4),
            "vr_difference": round(d["inversion"]["variance_reduction_plus1"] - d["inversion"]["variance_reduction_minus1"], 4),
            "best_plane_plus1": d["inversion"]["best_plane_plus1"]}


kept = [(p, t) for p, t in items if p.id not in excluded_ids]
by_track: dict = {}
for p, t in kept:
    by_track.setdefault(f"T{p.track}", []).append(t)
per_track_kept = {}
for name, tr in sorted(by_track.items()):
    fl = sign_decision.flipped(tr)
    fits = [(fit_plane(tr, pl), fit_plane(fl, pl)) for pl in ev.planes]
    best = max(fits, key=lambda f: max(f[0].variance_reduction, f[1].variance_reduction))
    per_track_kept[name] = {"vr_plus1": round(best[0].variance_reduction, 4), "vr_minus1": round(best[1].variance_reduction, 4),
                            "diff": round(best[0].variance_reduction - best[1].variance_reduction, 4)}
    print(VARIANT, name, per_track_kept[name], flush=True)
out = {"variant": VARIANT, "excluded_ids": sorted(excluded_ids), "per_frame": per_frame, "counts_all": counts(per_frame),
       "counts_kept": counts([r for r in per_frame if not r["excluded"]]), "per_track_kept": per_track_kept,
       "decision_kept": decide([t for _, t in kept])}
# the pooled decision on all pairs was already computed in sensitivity_iono_<V>.json (same code, same inputs)
prev = json.loads((OUT / f"sensitivity_iono_{VARIANT}.json").read_text(encoding="utf-8"))["decision_inputs"]
out["decision_all"] = {k: prev[k] for k in ("decision", "vr_plus1", "vr_minus1", "vr_difference", "best_plane_plus1", "ffm_n_k_positive_3sigma", "ffm_n_k_negative_3sigma")}
out["elapsed_s"] = round(time.time() - t0)
(OUT / f"ffm_by_variant_{VARIANT}.json").write_text(json.dumps(out, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
print("done", VARIANT, out["elapsed_s"], "s", flush=True)
