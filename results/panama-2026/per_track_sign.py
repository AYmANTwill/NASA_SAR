"""Per-track variance reduction of the fault fit with the LOS sign +1 and -1 (Panama M7.7, us6000u18k).

Run from backend/ (NISAR_LOS_SIGN unset):  python ../results/panama-2026/per_track_sign.py
For each track (T4, T40, T76, T141; the frames of a track are fitted together), each USGS nodal plane is fitted on the
data (+1) and on the flipped data (-1) with science.invert_fault.fit_plane (multi-start, no bootstrap, no noise model).
Writes per_track_sign.json and per_track_sign.md next to this file.

What this tests: with the fault geometry free to fit, an ascending and a descending track see the same ground motion
along different look vectors. The ascending/descending reversal therefore tests the LOS vectors (and the mechanism),
NOT the absolute sign: flipping the sign of one track flips its whole pattern, which the model can mimic only if the
mechanism allows it. Nothing here sets or verifies NISAR_LOS_SIGN.
"""
from __future__ import annotations

import json
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
import catalog  # noqa: E402
from recipes import displacement  # noqa: E402
from science import panama_fault as pf, sign_decision, usgs  # noqa: E402
from science.invert_fault import STARTS, fit_plane  # noqa: E402
import config  # noqa: E402

OUT = Path(__file__).resolve().parent
sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ev = usgs.event("us6000u18k")
origin = datetime.fromtimestamp(ev.time_ms / 1000, tz=timezone.utc).strftime("%Y%m%dT%H%M%S")
pairs = catalog.straddling(catalog.find(ev.lat, ev.lon, "GUNW"), origin)
rows, t_start = {}, time.time()
for p in pairs:
    track = f"T{p.track}"
    disp, coh, prof, notes, report = displacement.los_cm_full(p, corrections=("iono",))
    masked = np.where(coh >= pf.COH_MIN, disp, np.nan)
    valid_fraction = float(np.isfinite(masked).sum() / masked.size)
    t = pf.track_from_product(p, ev.lat, ev.lon)
    if t is None:
        continue
    r = rows.setdefault(track, {"direction": p.direction, "tracks": [], "pairs": [], "valid_fraction": {}})
    r["tracks"].append(t)
    r["pairs"].append(p.id)
    r["valid_fraction"][p.id] = round(valid_fraction, 4)
    del disp, coh, masked

out = {"event": ev.id, "los_sign_env": config.LOS_SIGN, "method": "fit_plane (multi-start), no bootstrap, no noise model",
       "starts": len(STARTS), "tracks": {}}
for name, r in sorted(rows.items()):
    tracks = r["tracks"]
    flipped = sign_decision.flipped(tracks)
    res = {"direction": r["direction"], "pairs": r["pairs"], "n_points": int(sum(t.los.size for t in tracks)),
           "valid_fraction_by_pair": r["valid_fraction"], "planes": []}
    for plane in ev.planes:
        fp, fm = fit_plane(tracks, plane), fit_plane(flipped, plane)
        res["planes"].append({"plane": vars(plane), "vr_plus1": round(fp.variance_reduction, 4),
                              "vr_minus1": round(fm.variance_reduction, 4), "rms_plus1_cm": round(fp.rms_cm, 2),
                              "rms_minus1_cm": round(fm.rms_cm, 2), "at_bound_plus1": fp.at_bound,
                              "at_bound_minus1": fm.at_bound})
    best = max(res["planes"], key=lambda x: max(x["vr_plus1"], x["vr_minus1"]))
    res["better_sign_best_plane"] = "+1" if best["vr_plus1"] > best["vr_minus1"] else "-1"
    res["vr_difference_best_plane"] = round(best["vr_plus1"] - best["vr_minus1"], 4)
    out["tracks"][name] = res
    print(name, res["direction"], res["n_points"], "pts", [(p["vr_plus1"], p["vr_minus1"]) for p in res["planes"]],
          flush=True)
out["elapsed_s"] = round(time.time() - t_start)
(OUT / "per_track_sign.json").write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")

lines = ["# Per-track sign test (generated by per_track_sign.py)", "",
         "Fit of each USGS nodal plane per track, data (+1) against flipped data (-1). No bootstrap, no noise model, "
         "multi-start fit. **The ascending/descending reversal tests the LOS vectors, not the absolute sign.**", "",
         "| Track | Dir | Points | Valid fraction (per pair) | Plane | VR(+1) | VR(-1) | Difference |", "|---|---|---|---|---|---|---|---|"]
for name, r in out["tracks"].items():
    vf = ", ".join(f"{k[-17:-9]}…:{v:.3f}" if False else f"{v:.3f}" for k, v in r["valid_fraction_by_pair"].items())
    for pl in r["planes"]:
        pr = pl["plane"]
        lines.append(f"| {name} | {r['direction'][:4]} | {r['n_points']} | {vf} | {pr['strike']}/{pr['dip']}/{pr['rake']} | "
                     f"{pl['vr_plus1']} | {pl['vr_minus1']} | {round(pl['vr_plus1'] - pl['vr_minus1'], 4)} |")
(OUT / "per_track_sign.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("done", out["elapsed_s"], "s")
