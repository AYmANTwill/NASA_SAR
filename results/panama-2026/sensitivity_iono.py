"""Sensitivity of the Panama sign test to the ionosphere screen, three variants (Panama M7.7, us6000u18k).

Run from backend/ (NISAR_LOS_SIGN unset), one process per variant (the displacement cache must not be shared):
    python ../results/panama-2026/sensitivity_iono.py A      # raw: the old already_applied (geocoding flags counted)
    python ../results/panama-2026/sensitivity_iono.py B      # fixed already_applied + per-pair keep_raw_phase rule (default code)
    python ../results/panama-2026/sensitivity_iono.py C      # forced subtraction (keep_raw_phase always False, in this script only)
    python ../results/panama-2026/sensitivity_iono.py G      # C again, through NISAR_IONO_GUARD=off (must match C)
    python ../results/panama-2026/sensitivity_iono.py merge  # sensitivity_iono.md from the three JSON files

Per track (frames fitted together, no bootstrap, no noise model): VR(+1), VR(-1) of each USGS nodal plane, points, valid
fraction (finite pixels after the coherence and uncertainty masks), whether each pair kept the raw phase, and the VR of the
ramp + offsets-only fit. Also the decision inputs of science.sign_decision on all tracks pooled. Nothing is tuned and
nothing in the repository is changed: the variants are monkeypatches inside this process.
"""
from __future__ import annotations

import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
OUT = Path(__file__).resolve().parent
VARIANT = sys.argv[1] if len(sys.argv) > 1 else "B"

import config  # noqa: E402
from recipes import corrections  # noqa: E402

if VARIANT == "A":                       # the code as it was: any flag with "iono" and "applied" counts, geocoding too
    def _old_already_applied(name, attrs):
        desc = ((attrs.get("datasets") or {}).get("unwrappedPhase") or {}).get("description", "").lower()
        if name in desc and any(w in desc for w in ("corrected", "applied", "removed")):
            return True
        hits = [v for k, v in (attrs.get("flags") or {}).items() if name in k.lower() and "applied" in k.lower()]
        if any(v.strip().lower() in corrections._TRUE for v in hits):
            return True
        return None if attrs.get("source") is None else False
    corrections.already_applied = _old_already_applied
elif VARIANT == "C":                     # forced subtraction
    corrections.keep_raw_phase = lambda *a, **k: False
elif VARIANT == "G":                     # same as C through the repository option NISAR_IONO_GUARD=off (no monkeypatch)
    os.environ["NISAR_IONO_GUARD"] = "off"


def merge() -> None:
    data = {v: json.loads((OUT / f"sensitivity_iono_{v}.json").read_text(encoding="utf-8")) for v in "ABC"}
    names = {"A": "A raw (old already_applied)", "B": "B fixed + keep_raw rule", "C": "C forced subtraction"}
    L = ["# Sensitivity of the Panama sign test to the ionosphere screen (generated by sensitivity_iono.py)", "",
         "No bootstrap, no noise model. Valid fraction = finite pixels after the coherence (0.3) and uncertainty masks.", ""]
    for v, d in data.items():
        L += [f"## Variant {names[v]}", "", "| Track | Dir | Points | Plane | VR(+1) | VR(-1) | Diff | Ramp-only VR |", "|---|---|---|---|---|---|---|---|"]
        for t, r in d["tracks"].items():
            for pl in r["planes"]:
                p = pl["plane"]
                L.append(f"| {t} | {r['direction'][:4]} | {r['n_points']} | {p['strike']}/{p['dip']}/{p['rake']} | {pl['vr_plus1']} | "
                         f"{pl['vr_minus1']} | {round(pl['vr_plus1'] - pl['vr_minus1'], 4)} | {r['vr_ramp_only_plus1']} |")
        L += ["", "| Pair | Iono applied | Kept raw | Frame sigma raw → subtracted (rad) | Uncertainty layer | Valid fraction |", "|---|---|---|---|---|---|"]
        for t, r in d["tracks"].items():
            for pid, i in r["pairs"].items():
                L.append(f"| {pid} | {i['applied']} | {i['kept_raw']} | {i['sigma_raw']} → {i['sigma_sub']} | {i['unc_layer']} | {i['valid_fraction']} |")
        dec = d["decision_inputs"]
        L += ["", f"Decision inputs (pooled): {json.dumps(dec, ensure_ascii=False)}", ""]
    ins = {v: data[v]["decision_inputs"] for v in data}
    keys = ["decision", "ffm_n_k_positive_3sigma", "ffm_n_k_negative_3sigma", "vr_plus1", "vr_minus1", "vr_difference", "best_plane_plus1"]
    L += ["## Do the decision inputs change?", "", "| Input | A | B | C |", "|---|---|---|---|"]
    for k in keys:
        L.append(f"| {k} | " + " | ".join(str(ins[v][k]) for v in "ABC") + " |")
    (OUT / "sensitivity_iono.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written sensitivity_iono.md")


if VARIANT == "merge":
    merge()
    sys.exit(0)

import catalog  # noqa: E402
from recipes import displacement  # noqa: E402
from science import panama_fault as pf, sign_decision, usgs  # noqa: E402
from science.invert_fault import fit_plane, ramp_design  # noqa: E402

ev = usgs.event("us6000u18k")
origin = datetime.fromtimestamp(ev.time_ms / 1000, tz=timezone.utc).strftime("%Y%m%dT%H%M%S")
pairs = catalog.straddling(catalog.find(ev.lat, ev.lon, "GUNW"), origin)
t0 = time.time()
rows, all_tracks = {}, []
for p in pairs:
    disp, coh, prof, notes, report = displacement.los_cm_full(p, corrections=("iono",))
    masked = np.where(coh >= pf.COH_MIN, disp, np.nan)
    i = report.get("iono", {})
    info = {"applied": bool(i.get("applied")), "kept_raw": bool(i.get("kept_raw")) if "kept_raw" in i else None,
            "already_applied_flag": i.get("already_applied_flag"), "reason": i.get("reason"),
            "sigma_raw": i.get("frame_sigma_raw_rad"), "sigma_sub": i.get("frame_sigma_subtracted_rad"),
            "unc_layer": i.get("uncertainty_layer"), "valid_fraction": round(float(np.isfinite(masked).sum() / masked.size), 4)}
    t = pf.track_from_product(p, ev.lat, ev.lon)
    if t is None:
        continue
    r = rows.setdefault(f"T{p.track}", {"direction": p.direction, "tracks": [], "pairs": {}})
    r["tracks"].append(t)
    r["pairs"][p.id] = info
    all_tracks.append(t)
    del disp, coh, masked


def ramp_only_vr(tracks) -> float:
    """VR of a fit with only each track's offsets (one per connected component) and east/north ramp, no fault."""
    res, dat = [], []
    for t in tracks:
        G = ramp_design(t.east, t.north, t.comp)
        coef = np.linalg.lstsq(G, t.los, rcond=None)[0]
        res.append(t.los - G @ coef)
        dat.append(t.los - np.median(t.los))
    r, d = np.concatenate(res), np.concatenate(dat)
    return round(1.0 - float(r @ r) / float(d @ d), 4) if d @ d > 0 else 0.0


out = {"variant": VARIANT, "los_sign_env": config.LOS_SIGN, "tracks": {}}
for name, r in sorted(rows.items()):
    tracks = r["tracks"]
    flipped = sign_decision.flipped(tracks)
    res = {"direction": r["direction"], "pairs": r["pairs"], "n_points": int(sum(t.los.size for t in tracks)),
           "vr_ramp_only_plus1": ramp_only_vr(tracks), "planes": []}
    for plane in ev.planes:
        fp, fm = fit_plane(tracks, plane), fit_plane(flipped, plane)
        res["planes"].append({"plane": vars(plane), "vr_plus1": round(fp.variance_reduction, 4),
                              "vr_minus1": round(fm.variance_reduction, 4), "rms_plus1_cm": round(fp.rms_cm, 2),
                              "rms_minus1_cm": round(fm.rms_cm, 2)})
    out["tracks"][name] = res
    print(VARIANT, name, res["n_points"], [(p["vr_plus1"], p["vr_minus1"]) for p in res["planes"]], flush=True)

dec = sign_decision.decide(all_tracks, ev.planes, ev.lat, ev.lon)
out["decision_inputs"] = {"decision": dec["decision"], "ffm_n_k_positive_3sigma": dec["ffm"]["n_k_positive_3sigma"],
                          "ffm_n_k_negative_3sigma": dec["ffm"]["n_k_negative_3sigma"],
                          "vr_plus1": round(dec["inversion"]["variance_reduction_plus1"], 4),
                          "vr_minus1": round(dec["inversion"]["variance_reduction_minus1"], 4),
                          "vr_difference": round(dec["inversion"]["variance_reduction_plus1"] - dec["inversion"]["variance_reduction_minus1"], 4),
                          "best_plane_plus1": dec["inversion"]["best_plane_plus1"],
                          "criteria_plus1": dec["criteria_plus1"],
                          "ffm_per_pair": {k: {"k_over_sigma": None if v["k_over_sigma"] is None else round(v["k_over_sigma"], 1), "verdict": v["verdict"]}
                                           for k, v in dec["ffm"]["per_track"].items()}}
out["elapsed_s"] = round(time.time() - t0)
(OUT / f"sensitivity_iono_{VARIANT}.json").write_text(json.dumps(out, indent=1, ensure_ascii=False, default=str), encoding="utf-8")
print("done", VARIANT, out["elapsed_s"], "s", flush=True)
