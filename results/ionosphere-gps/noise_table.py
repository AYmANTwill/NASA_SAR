"""Per-pair table: frame-wide robust sigma raw vs after subtracting the ionosphere screen, rad and cm, ratio raw/subtracted.

Run from backend/:  python ../results/ionosphere-gps/noise_table.py
Sources: results/panama-2026/sensitivity_iono_B.json (default code) and _C.json (forced subtraction) for the Panama
co-seismic pairs (sigma in rad, kept_raw flag); results/noise_with_without_iono_preliminary.csv for the Morocco pairs
(sigma in cm). cm <-> rad uses each pair's own wavelength (recipes/wavelength.py): cm = lambda/(4 pi) * rad * 100.
Read-only: nothing in the repository is changed; writes noise_table.json and noise_table.md next to this file.
"""
import csv, json, math, statistics, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
import catalog
from recipes import wavelength
OUT = Path(__file__).resolve().parent
R = OUT.parents[0]
prods = {p.id: p for p in catalog.load() if p.level == "GUNW"}
def lam(p): return wavelength.wavelength_m(p)
k = lambda l: l / (4 * math.pi) * 100            # cm per radian
rows_m, rows_p = [], []
for r in csv.DictReader(open(R / "noise_with_without_iono_preliminary.csv", encoding="utf-8")):
    p = next((q for q in prods.values() if q.track == int(r["track"]) and q.frame == int(r["frame"])
              and q.ref[:8] == r["ref"] and q.sec[:8] == r["sec"]), None)
    l, src = lam(p) if p else (None, "product not found")
    raw, sub = float(r["sigma_raw_cm"]), float(r["sigma_minus_iono_cm"])
    rows_m.append({"pair": f"T{r['track']} F{r['frame']} {r['direction']} {r['ref']}->{r['sec']}", "product": p.id if p else None,
                   "wavelength_m": l, "wavelength_source": src, "raw_cm": raw, "sub_cm": sub,
                   "raw_rad": None if not l else round(raw / k(l), 3), "sub_rad": None if not l else round(sub / k(l), 3),
                   "ratio": round(raw / sub, 2) if raw > 0 and sub > 0 else None, "kept_raw": None,
                   "note": "raw spread 0 (constant field): left out, as iono_chart does" if raw <= 0 else ""})
B = json.loads((OUT.parents[0] / "panama-2026/sensitivity_iono_B.json").read_text(encoding="utf-8"))
C = json.loads((OUT.parents[0] / "panama-2026/sensitivity_iono_C.json").read_text(encoding="utf-8"))
for t, tr in B["tracks"].items():
    for pid, i in tr["pairs"].items():
        c = C["tracks"][t]["pairs"][pid]
        l, src = lam(prods[pid])
        rr, rs = i["sigma_raw"], i["sigma_sub"]
        rows_p.append({"pair": pid, "wavelength_m": l, "wavelength_source": src, "raw_rad": rr, "sub_rad": rs,
                       "raw_cm": None if rr is None else round(rr * k(l), 2), "sub_cm": None if rs is None else round(rs * k(l), 2),
                       "ratio": round(rr / rs, 3) if rr and rs else None, "kept_raw": i["kept_raw"], "valid_fraction": i["valid_fraction"],
                       "uncertainty_layer": i["unc_layer"], "C_sub_rad": c["sigma_sub"]})
quiet = [r["ratio"] for r in rows_m if r["ratio"]]
q = statistics.quantiles(quiet, n=4, method="inclusive")
head = {"n_quiet_pairs_with_ratio": len(quiet), "n_morocco_rows": len(rows_m), "median_ratio": round(statistics.median(quiet), 2),
        "q1": round(q[0], 2), "q3": round(q[2], 2), "min": min(quiet), "max": max(quiet),
        "n_lower_after": sum(r["sub_cm"] < r["raw_cm"] for r in rows_m if r["ratio"]),
        "median_raw_cm": round(statistics.median(r["raw_cm"] for r in rows_m if r["ratio"]), 2),
        "median_sub_cm": round(statistics.median(r["sub_cm"] for r in rows_m if r["ratio"]), 2)}
pr = [r["ratio"] for r in rows_p if r["ratio"]]
head["panama_ratios"] = {"n": len(pr), "median": round(statistics.median(pr), 3), "min": min(pr), "max": max(pr),
                         "n_kept_raw": sum(bool(r["kept_raw"]) for r in rows_p)}
json.dump({"headline_quiet": head, "morocco_quiet": rows_m, "panama_coseismic": rows_p}, open(OUT / "noise_table.json", "w", encoding="utf-8"), indent=1, ensure_ascii=False)
L = ["# Frame-wide robust sigma, raw vs ionosphere screen subtracted (generated by noise_table.py)", "",
     "Frame-wide spread is not local accuracy. Ratio = raw / subtracted (> 1: subtracting lowers the spread). cm and rad use each pair's own wavelength.", "",
     "## Morocco (quiet pairs; preliminary CSV, kept_raw not recorded)", "", "| Pair | λ (m) | raw rad | sub rad | raw cm | sub cm | ratio | kept_raw |", "|---|---|---|---|---|---|---|---|"]
for r in rows_m: L.append(f"| {r['pair']} | {r['wavelength_m']} | {r['raw_rad']} | {r['sub_rad']} | {r['raw_cm']} | {r['sub_cm']} | {r['ratio']} | n/a {r['note']} |")
L += ["", "## Panama co-seismic pairs (earthquake signal inflates sigma; variant B = default code)", "", "| Pair | λ (m) | raw rad | sub rad | raw cm | sub cm | ratio | kept_raw | unc. layer |", "|---|---|---|---|---|---|---|---|---|"]
for r in rows_p: L.append(f"| {r['pair']} | {r['wavelength_m']} | {r['raw_rad']} | {r['sub_rad']} | {r['raw_cm']} | {r['sub_cm']} | {r['ratio']} | {r['kept_raw']} | {r['uncertainty_layer']} |")
L += ["", "Headline (quiet pairs): " + json.dumps(head, ensure_ascii=False), ""]
(OUT / "noise_table.md").write_text("\n".join(L), encoding="utf-8")
print(json.dumps(head, indent=1)); print("\n".join(L[5:]))
